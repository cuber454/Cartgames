package games.cardgames.speech

/**
 * Фразы, которые звучат одинаково в обеих играх.
 *
 * Держим их здесь, а не порознь по экранам: одно и то же событие за столом
 * должно и звучать одинаково. Разойдясь, такие фразы расходятся молча —
 * игрок слышит два разных слова про одно и то же и не знает, что думать.
 */

/**
 * Что бот скажет на своём ходу.
 *
 * [text] — реплика целиком; её же повторит кнопка «Повтори», если игрок не
 * расслышал. `speak = false` значит «промолчать»: звук хода сыграет, а слов
 * не будет. Реплика при этом не теряется — повторить её можно всегда.
 *
 * Живёт здесь, а не при том боте, который заговорил первым: реплика — это
 * то, что слышит игрок, и она одинакова у всех игр.
 */
data class BotLine(val text: String, val speak: Boolean)

/**
 * Ход вернулся к игроку: теперь ждут его.
 *
 * Нужна словами, а не только толчком с сигналом: молчание после хода бота
 * не отличить от «приложение задумалось», и игрок сидит и ждёт, пока
 * заговорит бот, которого уже никто не ждёт (Катерина, 18.09).
 */
const val TURN_PHRASE = "Твой ход."

/**
 * Та же фраза, но без слов о том, чей ход.
 *
 * Экран показывает последнюю фразу под столом — как «что сейчас сказали», —
 * а чей ход, и без неё написано в строке состояния над столом. Дважды об
 * одном и том же экран не говорит.
 *
 * Речь не трогаем: «Твой ход» на слух несёт переход (ход вернулся к игроку),
 * и его же повторяет «Повтори». Укорачиваем только надпись.
 */
fun withoutTurn(phrase: String): String = phrase.removeSuffix(TURN_PHRASE).trimEnd()
