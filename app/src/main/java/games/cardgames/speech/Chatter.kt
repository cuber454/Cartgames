package games.cardgames.speech

import games.cardgames.settings.Gender
import kotlin.random.Random

/**
 * Что стряслось за столом — повод для разговора.
 *
 * Поводы общие на все игры, а не свои у каждой: за столом разговор идёт об
 * одном и том же — я взял, я пропустил, у меня рука не пустеет, — и четыре
 * похожих набора поводов разошлись бы так же молча, как четыре похожих
 * банка фраз.
 *
 * Игра называет повод своими словами: в «Дураке» [TOOK] — забрал карты со
 * стола, в «101» — взял из колоды. Игроку разница слышна, слою — нет, и
 * незачем: реплика одна на оба случая.
 */
enum class TableEvent {
    /** Взял со стола или из колоды. */
    TOOK,

    /** Ходить нечем — ход пропущен. */
    PASSED,

    /** Рука не пустеет: карты прибывают быстрее, чем уходят. */
    FULL_HAND,

    /** Дама на выходе: в «101» она стоит вчетверо дороже прочих карт. */
    QUEEN,
}

/**
 * Разговоры за столом: слой, общий на все игры.
 *
 * За столом говорят не просто так, а о том, что стряслось: у реплики всегда
 * есть повод, и его называет игра ([TableEvent]). Слова лежат в общем банке
 * (`Phrases.kt`), поэтому «Дурак», «Тысяча», «Козёл» и «101» получают болтовню
 * одним и тем же слоем, а не четырьмя похожими (HUNDRED_ONE.md, 4.2).
 *
 * Три правила, без которых болтовня мешает слушать:
 *
 * - **одна реплика за кон**, и не в каждом: слот занимает первая же попытка,
 *   а молчит бот в трети случаев ([SILENT_OF]) — стол, где говорят на каждое
 *   событие, звучит механически;
 * - **реплика никогда не заменяет фразу о ходе**. Ход назван — потом
 *   комментарий; поэтому слой зовут после того, как экран сказал про ход, и
 *   `null` от него значит «промолчали», а не «сказано»;
 * - **ни чисел, ни карт**: названное число игрок проверяет по руке и сбивается
 *   с игры. Фразы подобраны так, что уточнять в них нечего.
 *
 * Фраза собирается из кусков — зачин × середина × концовка, — а не берётся
 * готовой: одиннадцать строк на повод дают сорок восемь реплик, и стол не
 * повторяется. Мешок помнит последнюю реплику и на стыке не повторяет её
 * ([PhraseBag]).
 */
class Chatter(private val rng: Random = Random.Default) {

    /** Часть реплики. Мешок свой у каждой: зачины не путаются с концовками. */
    private enum class Part { OPENER, MIDDLE, TAIL }

    /**
     * Из скольких реплик одна остаётся несказанной.
     *
     * Треть — не точная мера, а та, на которой стол перестаёт звучать
     * механически: реплика на каждое событие слышна как строка списка.
     */
    private val silentOf = 3

    private val bag = PhraseBag<Pair<TableEvent, Part>>(rng)

    /** Сказано ли уже в этом кону. */
    private var used = false

    /**
     * Сколько раз подряд стряслось не наше.
     *
     * Третья чужая неудача подряд — та самая полоса, на которой подколка
     * уступает место человеческому слову (HUNDRED_ONE.md, 4.3).
     */
    private var sadRun = 0

    /**
     * Новая раздача. Слот разговора свободен снова.
     *
     * В «Дураке» зовётся на новую партию: там разговор идёт один за всю игру.
     */
    fun newRound() {
        used = false
    }

    /**
     * Реплика на событие. `null` — бот промолчал.
     *
     * [own] — событие стряслось на своём ходу; иначе говорят о чужом, и там
     * слова другие: первое лицо в чужом ходу звучало бы как чужая речь.
     */
    fun line(event: TableEvent, own: Boolean): String? {
        if (used) return null
        used = true
        if (rng.nextInt(silentOf) == 0) return null

        val opener = bag.draw(event to Part.OPENER, TALK_OPENERS.getValue(event))
        val middle = bag.draw(
            event to Part.MIDDLE,
            if (own) TALK_MIDDLES_OWN.getValue(event) else TALK_MIDDLES_OTHER.getValue(event),
        )
        val tail = if (!own && sadRun >= 2) {
            // Тот же ключ, что и у обычной концовки: тёплая не повторяет
            // предыдущую только потому, что лежит в общем мешке с ней.
            bag.draw(event to Part.TAIL, TALK_WARM_TAILS)
        } else {
            bag.draw(event to Part.TAIL, TALK_TAILS.getValue(event))
        }
        sadRun = if (own) 0 else sadRun + 1

        val parts = listOf(opener, middle, tail).filter { it.isNotBlank() }
        // Зачин может быть пустым — тогда реплика начинается с середины, а
        // середина написана со строчной: с большой её делает эта строка, и
        // только она. Так зачин остаётся одним из вариантов, а не
        // обязательной частью.
        return parts.joinToString(" ").replaceFirstChar { it.uppercaseChar() }
    }
}

/**
 * Прибаутки: одна фраза на исход матча.
 *
 * Отдельно от [Chatter], и не только потому, что слышны в другой момент.
 * Разговор за столом идёт о ходе — прибаутка о партии; разговор ведёт тот,
 * чей ход, — прибаутку говорит приложение, потому что стола уже нет. Общее у
 * них одно: мешок, из которого тянут без возврата.
 */
class Jokes(private val rng: Random = Random.Default) {

    private val bag = PhraseBag<Boolean>(rng)

    /**
     * Фраза после матча: [won] — партия за игроком.
     *
     * [gender] — род игрока: прибаутка говорит о нём прошедшим временем, и
     * спрятать род в ней нечем (HUNDRED_ONE.md, 5).
     */
    fun afterMatch(won: Boolean, gender: Gender): String =
        gendered(bag.draw(won, if (won) JOKES_WIN else JOKES_LOSE), gender)
}
