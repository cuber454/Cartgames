package games.cardgames.speech

import games.engine.Card

/**
 * Вердикт по карте, до которой игрок дошёл пальцем: «подходит» или «не
 * подходит». Это ответ на вопрос «чем мне ходить», и только на него.
 *
 * Молчит, когда ходить нечем. В торге «Тысячи» карты не ходят вовсе, и
 * вердикт был бы враньём: «девятка пик, не подходит» звучит так, будто
 * девяткой нельзя сыграть, — а её просто пока не разыгрывают. То же в
 * «Дураке», когда ход у соперника: руку послушать можно, играть ею сейчас
 * нельзя. Молчание тут честнее слова, которое ничего не значит.
 *
 * [playable] — карты, которыми ход и вправду можно сделать (пусто — решать
 * сейчас не из чего).
 */
fun cardVerdict(card: Card, playable: Set<Card>): String = when {
    playable.isEmpty() -> ""
    card in playable -> ", подходит"
    else -> ", не подходит"
}
