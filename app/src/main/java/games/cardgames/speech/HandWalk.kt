package games.cardgames.speech

import games.engine.Card

/**
 * Подходит ли карта сейчас: `true` — можно сыграть, `false` — нельзя,
 * `null` — решать сейчас не из чего (нет игры, не наш ход, торг).
 *
 * [playable] — карты, которыми ход и вправду можно сделать. Пусто — значит
 * не из чего выбирать, и это не то же самое, что «ни одна не подходит».
 */
fun verdictOf(card: Card, playable: Set<Card>): Boolean? =
    if (playable.isEmpty()) null else card in playable

/**
 * Вердикт словами, как его слышит игрок: ответ на вопрос «чем мне ходить»
 * и только на него.
 *
 * Молчит, когда ходить нечем. В торге «Тысячи» карты не ходят вовсе, и
 * вердикт был бы враньём: «девятка пик, не подходит» звучит так, будто
 * девяткой нельзя сыграть, — а её просто пока не разыгрывают. То же в
 * «Дураке», когда ход у соперника, и то же на экране без партии: руку
 * послушать можно, играть ею сейчас нельзя. Молчание тут честнее слова,
 * которое ничего не значит. Одно правило на оба пути к карте — на свайп по
 * руке и на подпись самой карты: разойтись им нельзя, игрок услышит это
 * как два разных ответа про одну карту (Катерина, 18.09: «когда игры нет,
 * мне всё равно читает девятка бубна не подходит»).
 */
fun spokenVerdict(playable: Boolean?): String = when (playable) {
    null -> ""
    true -> ", подходит"
    false -> ", не подходит"
}

/** Вердикт по карте, до которой игрок дошёл пальцем или пальцем по экрану. */
fun cardVerdict(card: Card, playable: Set<Card>): String = spokenVerdict(verdictOf(card, playable))
