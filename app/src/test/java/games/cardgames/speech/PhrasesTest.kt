package games.cardgames.speech

import org.junit.Assert.assertEquals
import org.junit.Test

/**
 * Фраза, как её показывает экран.
 *
 * Речь и надпись расходятся нарочно: вслух «Твой ход» несёт переход, а в
 * надписи он повторял бы строку состояния. Разойтись молча они не должны —
 * если строка состояния однажды перестанет говорить, чей ход, эту правку
 * надо будет пересмотреть, а не чинить тест.
 */
class PhrasesTest {

    @Test
    fun `ход уходит из показанной фразы`() {
        assertEquals(
            "На столе: шесть пик.",
            withoutTurn("На столе: шесть пик. Твой ход."),
        )
    }

    /** Фраза из одного перехода: показывать нечего, и пустая строка честнее. */
    @Test
    fun `фраза из одного хода остаётся пустой`() {
        assertEquals("", withoutTurn(TURN_PHRASE))
    }

    /** Ход в середине фразы — это уже не «чей ход», а часть события. */
    @Test
    fun `ход в середине не трогаем`() {
        assertEquals(
            "Твой ход. Стол: шесть-пять.",
            withoutTurn("Твой ход. Стол: шесть-пять."),
        )
    }

    /** Фраза без слов о ходе остаётся как была. */
    @Test
    fun `фраза без хода не меняется`() {
        assertEquals("Беру. Из базара.", withoutTurn("Беру. Из базара."))
    }
}
