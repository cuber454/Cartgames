package games.engine.durak

/**
 * Договорённости сторон в «Дураке»: то, о чём сговариваются до раздачи.
 *
 * В «Дурака» играют по-разному не только в разных компаниях, но и в одной:
 * подкидной и переводной, ход из-под дурака — всё это уговор, а не правило.
 * Поэтому спорное живёт здесь, а не в коде хода: по книге играет тот, кому
 * так привычно, а своё включает тот, кто это своё знает (SETTINGS.md, 5).
 *
 * Набор принадлежит партии, а не экрану: начали по одним договорённостям —
 * по ним и доигрывают. Иначе выигранное по одному уговору окажется
 * проигранным по другому.
 *
 * [transfer] по умолчанию **включён**, в отличие от остальных: переводной
 * дурак был в приложении всегда, и обратное умолчание отняло бы у игрока
 * привычную игру молча.
 */
data class DurakRules(
    /** Перевод: защищающийся кладёт карту того же достоинства и передаёт атаку соседу. */
    val transfer: Boolean = true,

    /**
     * Дурак ходит первым в следующей партии.
     *
     * Книга: «В последующих партиях ходят либо из-под дурака, либо дурак».
     * Здесь из этих двух оставлен один — сам дурак. Вдвоём «из-под дурака»
     * значит «ходит победитель», то есть тот же выбор с другого конца, и
     * двумя переключателями его не выразить, не сделав один из них
     * перевёртышем другого.
     *
     * Прошлую партию проиграли — значит, её помнит партия, а не настройка:
     * кто дурак, знает только доигранная партия.
     */
    val loserLeads: Boolean = false,
) {

    /** Всё по книге — ни одной договорённости сверх неё. */
    val byTheBook: Boolean get() = this == BOOK

    companion object {
        val BOOK = DurakRules()
    }
}
