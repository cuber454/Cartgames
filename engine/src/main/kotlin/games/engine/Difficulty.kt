package games.engine

/**
 * Насколько хитро играет соперник.
 *
 * Живёт в корне движка, а не в «Дураке»: этажом выше его выбирают в
 * настройках, и он один на все игры — «Тысяча» берёт тот же.
 *
 * [NOVICE] играет наугад — его обыгрывает даже новичок.
 * [NORMAL] играет по здравому смыслу, но не помнит вышедших карт.
 * [CLEVER] считает вышедшие карты и прикидывает, чем противник ответит.
 */
enum class Difficulty(val title: String) {
    NOVICE("новичок"),
    NORMAL("обычный"),
    CLEVER("хитрый"),
    ;

    /** Следующий уровень по кругу — для кнопки выбора соперника. */
    fun next(): Difficulty = entries[(ordinal + 1) % entries.size]
}
