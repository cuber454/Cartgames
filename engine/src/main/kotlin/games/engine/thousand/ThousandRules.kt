package games.engine.thousand

/**
 * Договорённости сторон: правила, о которых сговариваются до стола.
 *
 * В «Тысячу» играют по-разному в разных компаниях, и расхождения тут — не
 * небрежность, а обычай: у одних самосвал, у других про него и не слышали.
 * Поэтому спорное живёт здесь выключенным флагом, а не зашитым в правила:
 * по книге играет тот, кому так привычно, а своё включает тот, кто это своё
 * знает (THOUSAND.md, 2.9; SETTINGS.md, 5).
 *
 * Флаги носит матч, а не экран. Партия помнит, по каким договорённостям её
 * начали, и до конца идёт по ним: переключение настройки посреди партии её
 * не меняет — иначе выигранное по одному счёту оказывалось бы проигранным
 * по другому.
 */
data class ThousandRules(
    /**
     * Самосвал: счёт, равный 555, сгорает в ноль.
     *
     * Именно ровно 555: перелёт через это число ничего не значит — самосвал
     * это попадание в само число, а не перевал через него.
     */
    val samosval: Boolean = false,
    /**
     * Штраф за роспись: третья роспись за партию стоит 120 — как третий
     * болт. Счётчик, как и у болтов, после штрафа начинается заново.
     */
    val raspisPenalty: Boolean = false,
    /**
     * Тузовый марьяж: четыре туза на руке к началу розыгрыша и хотя бы одна
     * взятая взятка дают 200 — в очки кона, а не сверх них.
     *
     * Именно в очки: 200 идут заказчику в его заказ, а защитнику в запись,
     * и от них же зависит, выполнен ли заказ. Марьяж обычный (король с дамой)
     * играется всегда и этой договорённостью не выключается.
     */
    val aceMarriage: Boolean = false,
    /**
     * Золотой кон: игрок с рукой на весь заказ (120 очков картами и
     * марьяжами) может объявить кон без торга — тогда он играется сразу на
     * 120, прикуп не берут, а очки и болты за него двойные.
     *
     * Порог — ровно заказ и ровно по руке: золотой кон объявляют не с
     * надеждой набрать, а с уже собранным. Прикуп в нём не берут, поэтому
     * играть приходится тем, что сдано.
     */
    val golden: Boolean = false,
) {
    /** Все договорённости выключены — игра по книге. */
    val byTheBook: Boolean get() = this == BOOK

    companion object {
        /** По книге: ни одной включённой договорённости. */
        val BOOK = ThousandRules()
    }
}
