package games.engine.tiles

/**
 * Порядок костей на руке.
 *
 * Рука листается вслепую — на слух и свайпами, — поэтому порядок здесь не
 * украшение, а способ найти нужную кость: он один на всю игру и не меняется
 * от хода к ходу. Какой из двух лучше, решает игрок, а не мы: у обоих есть
 * свой резон, и оба применяются за столом.
 *
 * Дом у порядка один — тяжёлое впереди. Тяжёлая кость и сбрасывается
 * первой, и стоит дороже всех, если останется на руке: держать её под
 * пальцем, а не искать по всей руке, удобнее.
 */
enum class TileOrder(val title: String) {

    /**
     * По числам: рядом кости, у которых есть общее число, — все шестёрки
     * подряд, за ними все пятёрки и так далее.
     *
     * Так рука отвечает на вопрос, который за столом задают чаще всего:
     * «чем мне ответить на шестёрку». Пролистал руку — и все шестёрки уже
     * рядом, искать по одной не надо.
     */
    BY_NUMBERS("по числам, одинаковые рядом"),

    /**
     * По весу: сверху самые тяжёлые по сумме точек — 6-6, 6-5, 5-5.
     *
     * Так рука показывает, что сбрасывать: порядок совпадает с порядком
     * сброса, и первая кость в руке — та, от которой хочется избавиться.
     */
    BY_PIPS("по весу, тяжёлые сверху");

    /**
     * Рука в этом порядке.
     *
     * Сортировка полная и однозначная: у каждой кости своё место, повторов
     * в наборе не бывает. При равном весе (6-4 и 5-5 — обе по десять)
     * вперёд идёт та, у которой старшая половина больше: иначе две руки с
     * одним и тем же набором костей лежали бы по-разному.
     */
    fun sort(tiles: List<Tile>): List<Tile> = when (this) {
        BY_NUMBERS -> tiles.sortedWith(compareByDescending<Tile> { it.high }.thenByDescending { it.low })
        BY_PIPS -> tiles.sortedWith(
            compareByDescending<Tile> { it.pips }.thenByDescending { it.high }.thenByDescending { it.low },
        )
    }

    /** Следующий порядок по кругу — для кнопки «Порядок костей». */
    fun next(): TileOrder = entries[(ordinal + 1) % entries.size]
}
