package games.engine.tiles

import kotlin.random.Random

/** Старшая половина кости в наборе «дубль-шесть». */
const val TILE_MAX = 6

/** Сколько костей в наборе «дубль-шесть»: все пары чисел от нуля до шести. */
const val TILE_COUNT = 28

/**
 * Как число на половине кости называется вслух.
 *
 * Ноль — «пусто», а не «ноль»: в домино это пустая половина, и «пусто-три»
 * за столом понятнее, чем «ноль-три». Слова одни на всех — ими говорит и
 * подпись кости, и объявление концов, — поэтому имя живёт здесь.
 */
fun pipsName(pips: Int): String = when (pips) {
    0 -> "пусто"
    1 -> "один"
    2 -> "два"
    3 -> "три"
    4 -> "четыре"
    5 -> "пять"
    6 -> "шесть"
    else -> pips.toString()
}

/**
 * Кость домино: две половины, на каждой от нуля до шести точек.
 *
 * Половины хранятся по возрастанию ([low] меньше или равна [high]), так что
 * у одной кости ровно одно представление и сравнение костей не врёт.
 * Называем же вслух старшую первой, как принято за столом: кость 3-6 — это
 * «шесть-три».
 *
 * [pips] — точки на кости: они и очки при подсчёте, и вес при сбросе.
 */
data class Tile(val low: Int, val high: Int) {
    init {
        require(low in 0..TILE_MAX && high in 0..TILE_MAX) { "половина кости вне набора: $low-$high" }
        require(low <= high) { "половины кости пишутся по возрастанию, а не $low-$high" }
    }

    val pips: Int get() = low + high

    /** Дубль — кость с одинаковыми половинами; её кладут поперёк линии. */
    val isDouble: Boolean get() = low == high

    /** Есть ли на кости это число. */
    fun has(pips: Int): Boolean = low == pips || high == pips

    /**
     * Вторая половина кости: та, которой кость останется наружу, если
     * приставить её половиной [pips].
     *
     * У дубля обе половины равны, поэтому наружу у него смотрит то же число:
     * дубль занимает конец и оставляет его тем же.
     */
    fun other(pips: Int): Int = if (low == pips) high else low

    /** Как кость называется вслух: «шесть-три», «пусто-пусто». */
    fun spoken(): String = "${pipsName(high)}-${pipsName(low)}"

    override fun toString(): String = spoken()
}

/** Кость по двум половинам в любом порядке: `tile(6, 3)` — та же, что `tile(3, 6)`. */
fun tile(a: Int, b: Int): Tile = Tile(minOf(a, b), maxOf(a, b))

/**
 * Набор костей «дубль-шесть» — 28 штук, каждая пара чисел ровно один раз.
 *
 * Тасовка живёт здесь же, а не в раунде: раздача вслепую — это свойство
 * набора, и проверять его честность тестами удобнее всего тут.
 */
object TileSet {

    /** Полный набор: от пусто-пусто до шесть-шесть. */
    val full: List<Tile> = (0..TILE_MAX).flatMap { low ->
        (low..TILE_MAX).map { high -> Tile(low, high) }
    }

    init {
        check(full.size == TILE_COUNT) { "в наборе «дубль-шесть» должно быть $TILE_COUNT костей" }
    }

    /**
     * Перетасованный набор. Тасуется обычным [Random.shuffle], то есть все
     * перестановки равновероятны: ни одна кость не «любимее» другой, и
     * порядок в базаре никому не известен — ни игроку, ни боту.
     */
    fun shuffled(random: Random): MutableList<Tile> = full.shuffled(random).toMutableList()
}
